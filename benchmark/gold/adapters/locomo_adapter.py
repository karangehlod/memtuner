"""LoCoMo dataset adapter — delegates to benchmark.gold.locomo_loader.

The authoritative LoCoMo parser is LoCoMoLoader in benchmark/gold/locomo_loader.py.
This module provides a DatasetAdapter-compatible wrapper for consistency with
other adapters, using IDs generated by LoCoMoLoader (LCM-* scheme) which matches
what GoldOracle.load_dataset() produces for the same source file.

Previous versions of this file attempted to parse LoCoMo's raw JSON format
independently, producing `mem_{day}_{event_idx}` IDs incompatible with the
oracle path. That class is replaced by this delegation to avoid ID-scheme split.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from benchmark.gold.adapters.adapter import DatasetAdapter, ValidationReport
from benchmark.gold.schema import GoldDataset


class LoCoMoAdapter(DatasetAdapter):
    """DatasetAdapter wrapper around LoCoMoLoader.

    Produces the same LCM-* memory IDs as GoldOracle.load_dataset() so that
    gold JSON files generated via this adapter are compatible with oracle-based
    benchmarking.
    """

    name = "locomo"

    def load(self, source: Path | str) -> GoldDataset:
        """Load LoCoMo dataset via the canonical LoCoMoLoader.

        Args:
            source: Path to locomo10.json or similar LoCoMo raw JSON file.

        Returns:
            GoldDataset with LCM-* memory IDs.
        """
        import json

        from benchmark.gold.locomo_loader import LoCoMoLoader

        source = Path(source)
        try:
            raw_data = json.loads(source.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as e:
            from benchmark.gold.adapters.adapter import AdapterError
            raise AdapterError(f"Cannot read LoCoMo file {source}: {e}") from e

        loader = LoCoMoLoader()
        return loader.convert_raw(raw_data, scenario_name="locomo")

    def validate(self, dataset: GoldDataset) -> ValidationReport:
        """Validate LoCoMo dataset using the standard registry."""
        from benchmark.gold.validators import ValidationRegistry
        return ValidationRegistry.validate_all(dataset)

    def fingerprint(self, dataset: GoldDataset) -> str:
        """Generate fingerprint for the loaded dataset."""
        import hashlib
        query_ids = sorted(q.query for q in dataset.queries)
        memory_ids = sorted(m.id for day in dataset.events for m in day.memory_events)
        fp_data = {"queries": query_ids[:50], "memories": memory_ids[:50]}
        return hashlib.sha256(str(fp_data).encode()).hexdigest()[:32]

    def statistics(self, dataset: GoldDataset) -> Any:
        """Compute dataset statistics."""
        from benchmark.gold.statistics import StatisticsComputer
        return StatisticsComputer.compute(dataset)
